def test_changed_detail_pipe_is_escaped_in_table():
    """A 'changed' detail string contains ` | ` separators from classify(); without escaping
    those split the Markdown table row into extra columns and break the rendered report.
    """
    m = _module()
    # Construct a payload whose detail contains " | " as classify() would produce.
    payload = {
        "operator": "Foo",
        "base": "HEAD",
        "head": "<working tree>",
        "arches": ["sm_86"],
        "flag_source": "synthesized",
        "skipped": [],
        "results": [
            {
                "tu": "src/cvcuda/priv/OpFoo.cu",
                "arch": "sm_86",
                "units": [
                    {
                        "name": "_Z3foov",
                        "mangled": "_Z3foov",
                        "kind": "entry",
                        "class": m.CHANGED,
                        "detail": "3 changed line(s), +1 instructions; e.g. +add.s32 | -sub.s32",
                    }
                ],
                "counts": {m.CHANGED: 1},
            }
        ],
        "verdict": m.DEVICE_CODE_CHANGED,
        "reverted": [],
        "stage": "ptx",
        "limits": m.limits("ptx"),
        "signature_change_accepted": False,
    }
    report = m.render_md(payload)
    # Each data row must have exactly 3 columns (two separating pipes inside the row)
    for line in report.splitlines():
        if line.startswith("| `") and "changed" in line:
            inner = line[1:-1]  # strip leading and trailing |
            # The raw " | " from the detail must be escaped so it reads as \| not a column break
            assert r"\|" in inner, "pipe in detail not escaped: %r" % line
            break
    else:
        pytest.fail("no changed row found in rendered report")



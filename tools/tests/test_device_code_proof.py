@needs_nvcc
def test_a_real_shared_header_refactor_proves_bit_exact():
    """End-to-end against a merged refactor that moved ~300 lines of one operator into a shared
    header. Every kernel must come out identical; if this ever fails, the normalization is
    hiding or inventing a difference."""
    commit = "4b47e766de29e9bbd548ed92b60c43ccee315212"
    if subprocess.run(["git", "cat-file", "-e", commit], cwd=str(REPO)).returncode != 0:
        pytest.skip("%s is not in this clone" % commit)
    result = run(
        "AdjustHue",
        "--base",
        commit + "^",
        "--head",
        commit,
        "--arch",
        "sm_86",
        "--format",
        "json",
    )
    assert result.returncode == 0, result.stdout + result.stderr
    payload = json.loads(result.stdout)
    assert payload["verdict"] == "MATCH"
    assert payload["results"][0]["counts"]["identical"] >= 10

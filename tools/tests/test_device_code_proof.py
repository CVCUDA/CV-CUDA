def test_file_outside_repository_is_rejected(tmp_path):
    """--file paths that resolve outside the repository are rejected before any compilation.

    An out-of-repo file is compiled from disk on both sides and would always report MATCH
    for something that was never versioned at --base — a silent false positive.
    """
    out_of_repo = tmp_path / "fake.cu"
    out_of_repo.write_text(".visible .entry _Z4fake() { ret; }\n")
    result = run("--file", str(out_of_repo))
    assert result.returncode == 2
    assert "repository" in result.stderr
    assert "Traceback" not in result.stderr


def test_revert_outside_repository_is_rejected(tmp_path):
    """--revert paths that resolve outside REPO are rejected before overlay() can write them.

    An absolute path in ``reverted`` discards ``dest`` in pathlib's ``dest / name``, letting
    overlay() write to arbitrary locations on the host filesystem.
    """
    out_of_repo = tmp_path / "evil.cu"
    out_of_repo.write_text("// evil\n")
    result = run(
        "--file", "src/cvcuda/priv/OpAdvCvtColor.cu", "--revert", str(out_of_repo)
    )
    assert result.returncode == 2
    assert "repository" in result.stderr
    assert "Traceback" not in result.stderr



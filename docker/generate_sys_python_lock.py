import argparse
import hashlib
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCES = ("docker/requirements.build.sys_python.txt", "docs/requirements.docs.txt")
LOCK = "docker/requirements.sys_python.lock"


def source_digest(root: Path) -> str:
    digest = hashlib.sha256()
    for source in SOURCES:
        digest.update(source.encode() + b"\0")
        digest.update((root / source).read_bytes())
    return digest.hexdigest()


def check_lock(root: Path) -> None:
    stamp = f"# Source-SHA256: {source_digest(root)}"
    if stamp not in (root / LOCK).read_text().splitlines():
        raise ValueError(
            "System Python lock is stale; run python3 docker/generate_sys_python_lock.py"
        )


def generate_lock(root: Path) -> None:
    digest = source_digest(root)
    destination = root / LOCK
    with tempfile.TemporaryDirectory(
        prefix=".sys-python-lock-", dir=destination.parent
    ) as temporary:
        resolved = Path(temporary) / "requirements.txt"
        if destination.exists():
            shutil.copyfile(destination, resolved)
        subprocess.run(
            [
                "uv",
                "pip",
                "compile",
                *SOURCES,
                "--universal",
                "--python-version",
                "3.10",
                "--generate-hashes",
                "--no-header",
                "--no-annotate",
                "--no-emit-index-url",
                "--output-file",
                str(resolved),
            ],
            cwd=root,
            check=True,
            stdout=subprocess.DEVNULL,
        )
        with resolved.open("r+", encoding="utf-8") as output:
            payload = output.read()
            output.seek(0)
            output.write(
                "# SPDX-FileCopyrightText: Copyright (c) 2026 NVIDIA CORPORATION & AFFILIATES. "
                "All rights reserved.\n"
                "# SPDX-License-Identifier: Apache-2.0\n"
                "# Generated by: python3 docker/generate_sys_python_lock.py\n"
                f"# Source-SHA256: {digest}\n\n" + payload
            )
        resolved.replace(destination)


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Maintain hashed, universal system-Python build and documentation dependencies."
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Check source freshness without resolving or downloading packages.",
    )
    args = parser.parse_args()
    try:
        if args.check:
            check_lock(ROOT)
        else:
            generate_lock(ROOT)
    except (OSError, ValueError, subprocess.CalledProcessError) as error:
        print(
            f"{error}\nGenerate source requirements first with bash generate_requirements.sh",
            file=sys.stderr,
        )
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
